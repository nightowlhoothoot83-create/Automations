import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { buildDashboard } from '../src/hub/model.mjs';
import { loadWorkerRunDetails } from '../src/hub/workers.mjs';

const dashboard = await buildDashboard();
const workerIds = (dashboard.workers || []).map((worker) => worker.id);
const workers = Object.fromEntries(await Promise.all(workerIds.map(async (id) => [id, await loadWorkerRunDetails(id)])));
const output = resolve('functions/_generated.js');
await mkdir(resolve('functions'), { recursive: true });
await writeFile(output, `// Generated by scripts/build-hub-pages.mjs; do not edit.\nexport const dashboardSnapshot = ${JSON.stringify(dashboard, null, 2)};\nexport const workerSnapshots = ${JSON.stringify(workers, null, 2)};\n`);
console.log(JSON.stringify({ output, workers: workerIds.length, mode: dashboard.mode }));
